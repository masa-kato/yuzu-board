def suggest_name(taken, letter, avoid=(), rng=random):
    """An unused noun for `letter`; falls back to "Falcon 2" style names once
    every noun for that letter is in use."""
    used = {t.lower() for t in taken if t} | {a.lower() for a in avoid if a}
    options = [n for n in NOUNS[letter] if n.lower() not in used]
    if options:
        return rng.choice(options)
    n = 2
    while True:
        for noun in NOUNS[letter]:
            candidate = "%s %d" % (noun, n)
            if candidate.lower() not in used:
                return candidate
        n += 1


def starts_with_letter(name, letter):
    return bool(name) and name[0].upper() == letter.upper()
